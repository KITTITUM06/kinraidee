def seed_database():
    db_path = "kinraidee.db"
    conn = sqlite3.connect(db_path)
    cursor = conn.cursor()

    # ล้างตารางเดิมทิ้งเพื่อเริ่มนับ ID 1 ใหม่
    cursor.execute("DROP TABLE IF EXISTS menus")

    # สร้างตารางโดยใช้ชื่อฟิลด์ recipe_summary ให้ตรงกับ Model ใน main.py
    cursor.execute("""
    CREATE TABLE IF NOT EXISTS menus (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        name TEXT NOT NULL,
        category TEXT NOT NULL,
        price REAL,
        calories INTEGER,
        spiciness INTEGER,
        ingredients TEXT,
        restaurant_name TEXT,
        image_url TEXT,
        recipe_summary TEXT,
        random_count INTEGER DEFAULT 0
    )
    """)

    # บันทึกข้อมูลเมนูทั้ง 20 รายการ
    query = """
    INSERT INTO menus (name, category, price, calories, spiciness, ingredients, restaurant_name, image_url, recipe_summary, random_count)
    VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
    """
    cursor.executemany(query, MENUS_NU)

    conn.commit()
    conn.close()
    print("✅ นำเข้าร้านดัง มอนอ พร้อมเมนูจริงตามรีวิว ลงฐานข้อมูล kinraidee.db สำเร็จเรียบร้อยแล้ว!")

if __name__ == "__main__":
    seed_database()